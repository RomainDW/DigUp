import AppKit
import DigUpKit
import Observation

/// One thing that was copied: a text, a picture or files.
nonisolated struct ClipItem: Codable, Identifiable, Equatable, Sendable {
    enum Kind: String, Codable, Sendable { case text, image, files }
    /// Whether the history shows it: masked until checked, and for good if it looks explicit (⌘U shows it).
    enum Safety: String, Codable, Sendable { case unchecked, safe, explicit }

    var id = UUID()
    var date = Date()
    let kind: Kind
    var text: String?
    /// The picture, saved as PNG in the history's folder.
    var imageFile: String?
    var paths: [String]?
    /// The app it was copied from.
    var source: String?
    var safety = Safety.unchecked

    var rowID: String { ClipboardHistory.rowPrefix + id.uuidString }
    var masked: Bool { safety != .safe }

    /// What it's found by and shown as in the list.
    var title: String {
        switch kind {
        case .text: (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
                .replacingOccurrences(of: "\n", with: " ⏎ ")
        case .image: "Picture"
        case .files: (paths ?? []).map { ($0 as NSString).lastPathComponent }.joined(separator: ", ")
        }
    }

    /// The same content: copying it again moves the old one to the top instead of adding it twice.
    func sameContent(as other: ClipItem) -> Bool {
        kind == other.kind && text == other.text && paths == other.paths && kind != .image
    }
}

/// The clipboard history (fork): everything copied, newest first, kept on disk, searched with "clip:" in the panel.
/// Password managers' copies (marked concealed or transient) are never kept. What looks explicit is masked
/// (`SafetyFilter`, `ImageSafetyChecker`); ⌘U shows it while the panel is open.
@Observable
final class ClipboardHistory {
    nonisolated static let rowPrefix = "\u{0}clip:"
    static let limit = 300
    static let pollInterval: TimeInterval = 0.5
    /// Pasteboard types that mean "don't keep this" (nspasteboard.org's conventions, 1Password, KeePassXC…).
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
        "com.typeit4me.clipping", "net.antelle.keeweb",
    ]

    private(set) var items: [ClipItem] = []

    @ObservationIgnored private let folder: URL
    @ObservationIgnored private let checker: ImageSafetyChecker
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var saveTask: Task<Void, Never>?

    init(engine: Engine) {
        // Beside the index (Application Support/DigUp; .dev in dev runs, so they never see the real history).
        folder = engine.indexDirectory.deletingLastPathComponent().appendingPathComponent("Clipboard")
        checker = ImageSafetyChecker(modelsDirectory: engine.modelsDirectory,
                                     logFile: engine.indexDirectory.appendingPathComponent("worker-safety.log"))
        try? FileManager.default.createDirectory(at: folder.appendingPathComponent("images"),
                                                 withIntermediateDirectories: true)
        load()
    }

    private var historyFile: URL { folder.appendingPathComponent("history.json") }

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
        // Anything left unchecked last time (the model wasn't there, or the app quit first).
        for item in items where item.safety == .unchecked { check(item) }
    }

    // MARK: Searching

    /// Newest first; with text, the ones whose text, file names or source app contain every word typed. Masked ones
    /// are found by their source and date only, so their words don't show up in a search.
    func matches(_ query: String) -> [ClipItem] {
        let words = query.lowercased().split(separator: " ").map(String.init)
        guard !words.isEmpty else { return items }
        return items.filter { item in
            let haystack = ((item.masked ? "" : item.title + " " + (item.paths ?? []).joined(separator: " "))
                + " " + (item.source ?? "") + (item.kind == .image ? " picture image photo" : "")).lowercased()
            return words.allSatisfy { haystack.contains($0) }
        }
    }

    func item(withRowID id: String) -> ClipItem? {
        guard id.hasPrefix(Self.rowPrefix) else { return nil }
        return items.first { $0.rowID == id }
    }

    func imageURL(_ item: ClipItem) -> URL? {
        item.imageFile.map { folder.appendingPathComponent("images").appendingPathComponent($0) }
    }

    // MARK: Copying back, removing

    /// Puts it back on the clipboard, and at the top of the history.
    func copy(_ item: ClipItem, to pasteboard: NSPasteboard = .general) {
        pasteboard.clearContents()
        switch item.kind {
        case .text: pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let url = imageURL(item), let image = NSImage(contentsOf: url) { pasteboard.writeObjects([image]) }
        case .files: pasteboard.writeObjects((item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        if pasteboard == .general { lastChange = pasteboard.changeCount }
        var moved = item
        moved.date = Date()
        items.removeAll { $0.id == item.id }
        items.insert(moved, at: 0)
        save()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        if let url = imageURL(item) { try? FileManager.default.removeItem(at: url) }
        save()
    }

    func removeAll() {
        for item in items { if let url = imageURL(item) { try? FileManager.default.removeItem(at: url) } }
        items = []
        save()
    }

    // MARK: Watching the clipboard

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName
        var item: ClipItem?
        let string = pasteboard.string(forType: .string)
        // A picture copied in a browser comes with its address as text: it's the picture that was copied.
        let hasPicture = !types.isDisjoint(with: ["public.png", "public.tiff", "public.jpeg", "public.heic"])
        let textIsJustALink = string.map { !$0.contains(" ") && !$0.contains("\n") && URL(string: $0)?.scheme != nil }
            ?? true
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true])
            as? [URL], !urls.isEmpty {
            item = ClipItem(kind: .files, paths: urls.map(\.path), source: source)
        } else if let text = string, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
                  !(hasPicture && textIsJustALink) {
            item = ClipItem(kind: .text, text: String(text.prefix(100_000)), source: source)
        } else if let image = NSImage(pasteboard: pasteboard), let png = Self.png(image) {
            let name = UUID().uuidString + ".png"
            do {
                try png.write(to: folder.appendingPathComponent("images").appendingPathComponent(name))
                item = ClipItem(kind: .image, imageFile: name, source: source)
            } catch {
                log("clipboard: can't save a picture: \(error)")
            }
        }
        guard let item else { return }
        add(item)
    }

    private func add(_ new: ClipItem) {
        var item = new
        if let old = items.first(where: { $0.sameContent(as: new) }) {
            item.safety = old.safety   // already checked
            items.removeAll { $0.id == old.id }
        }
        items.insert(item, at: 0)
        while items.count > Self.limit {
            let dropped = items.removeLast()
            if let url = imageURL(dropped) { try? FileManager.default.removeItem(at: url) }
        }
        save()
        if item.safety == .unchecked { check(item) }
    }

    /// Words and sites first (at once), then the model: by meaning for a text, by what it shows for a picture (a
    /// copied picture file too). Until the model has answered, it stays masked.
    private func check(_ item: ClipItem) {
        let words = [item.text, item.paths?.joined(separator: " "), item.source].compactMap { $0 }.joined(separator: " ")
        if SafetyFilter.isExplicit(text: words) {
            setSafety(.explicit, of: item.id)
            return
        }
        let picture: String? = switch item.kind {
        case .image: imageURL(item)?.path
        case .files: item.paths?.first { ["png", "jpg", "jpeg", "heic", "webp", "gif", "tiff", "bmp"]
                .contains(($0 as NSString).pathExtension.lowercased()) }
        case .text: nil
        }
        let text = item.kind == .text ? item.text : nil
        Task {
            var explicit: Bool?
            if let picture {
                explicit = await checker.isExplicit(imageAt: picture)
            } else if let text {
                explicit = await checker.isExplicit(text: text)
            } else {
                explicit = false   // files that aren't pictures: their names were checked above
            }
            guard let explicit else { return }   // couldn't check: stays masked, tried again next launch
            setSafety(explicit ? .explicit : .safe, of: item.id)
        }
    }

    private func setSafety(_ safety: ClipItem.Safety, of id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].safety = safety
        save()
    }

    // MARK: Disk

    private func load() {
        guard let data = try? Data(contentsOf: historyFile) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .secondsSince1970
        items = (try? decoder.decode([ClipItem].self, from: data)) ?? []
    }

    /// Soon after the last change, off the main thread (a picture's history entry is small, the PNG is already saved).
    private func save() {
        saveTask?.cancel()
        let snapshot = items, file = historyFile
        saveTask = Task {
            try? await Task.sleep(for: .milliseconds(300))
            guard !Task.isCancelled else { return }
            await Task.detached(priority: .utility) {
                let encoder = JSONEncoder()
                encoder.dateEncodingStrategy = .secondsSince1970
                if let data = try? encoder.encode(snapshot) { try? data.write(to: file, options: .atomic) }
            }.value
        }
    }

    private static func png(_ image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }
}

/// "clip: invoice": a search of the clipboard history, and nothing else (like "code:").
nonisolated enum ClipQuery {
    static let prefixes = ["clip:", "cb:"]

    /// What's typed after the prefix ("" for "clip:" alone), or nil for a search that isn't one of the clipboard.
    static func text(of query: String) -> String? {
        let trimmed = query.drop { $0.isWhitespace }
        for prefix in prefixes where trimmed.lowercased().hasPrefix(prefix) {
            return trimmed.dropFirst(prefix.count).trimmingCharacters(in: .whitespacesAndNewlines)
        }
        return nil
    }
}
